def load_sources():
    for p in sorted(SRC.glob("*.json")):
        j = json.loads(p.read_text())
        sid = j["source_id"]
        SOURCES[sid] = j
        for f in j.get("facts", []):
            fid = f.get("fact_id")
            if not fid:
                PROBLEMS.append(f"{sid}: fact without fact_id: {str(f)[:80]}"); continue
            if fid in FACTS:
                PROBLEMS.append(f"duplicate fact_id {fid} ({sid} and {FACTS[fid]['_source']})"); continue
            FACTS[fid] = {**f, "_source": sid}


def fact(fid: str) -> dict:
    if fid not in FACTS:
        raise KeyError(f"missing fact {fid}")
    return FACTS[fid]


def fact_opt(fid: str):
    return FACTS.get(fid)


def page_int(page) -> int:
    """First integer in a page field ('sch 47' → 47, '24-26' → 24, 'unknown' → 0). 0 means 'page not determinable from the text'."""
    if page is None:
        return 0
    if isinstance(page, int):
        return page
    m = re.search(r"\d+", str(page))
    return int(m.group()) if m else 0


def page_label(f: dict) -> str:
    sec = str(f.get("section") or "")
    p = f.get("page")
    part = ""
    for name in ("Attachment A", "Attachment B"):
        if sec.startswith(name):
            part = name + " "
    if p is None or str(p).lower().startswith("unknown") or str(p).lower() == "none":
        return "page not determinable from the text extraction"
    return f"{part}p.{p}"


def cite(fid: str, doc_label: str | None = None) -> dict:
    f = fact(fid)
    if not f.get("quote"):
        raise ValueError(f"fact {fid} has no quote — cannot cite")
    return {"doc": doc_label or LABELS[f["_source"]], "page": page_int(f.get("page")), "page_note": page_label(f), "quote": f["quote"],
            "section": f.get("section"), "fact_id": fid, "review_status": f.get("review_status")}


def V(fid: str, value=None, status: str | None = None, note: str = "", doc_label: str | None = None, use_fact_value=True) -> dict:
    f = fact(fid)
    st = status or f.get("status", "DOC")
    out = {"value": (f.get("value") if (value is None and use_fact_value) else value), "status": st, "note": note or (f.get("notes") or "")[:400]}
    if f.get("quote"):
        out["cite"] = cite(fid, doc_label)
    if st == "UNKNOWN":
        out["value"] = None
    return out


def unknown(note: str, fid: str | None = None) -> dict:
    out = {"value": None, "status": "UNKNOWN", "note": note}
    if fid:
        out["fact_id"] = fid
    return out


def pct_to_bp_plan_pays(f: dict) -> int:
    """Convert a coinsurance fact to basis points the PLAN pays. Facts record the basis explicitly (unit)."""
    unit = f.get("unit")
    if unit == "percent_plan_pays":
        return int(f["value"]) * 100
    if unit == "percent_you_pay":
        return (100 - int(f["value"])) * 100
    raise ValueError(f"coinsurance fact {f['fact_id']} has unit {unit!r}")


def coins(fid: str, extra_note: str = "") -> dict:
    f = fact(fid)
    bp = pct_to_bp_plan_pays(f)
    note = ("document states what YOU pay; plan share = 100% − that. " if f.get("unit") == "percent_you_pay" else "") + extra_note
    return {"value": bp, "status": f.get("status", "DOC"), "cite": cite(fid), "note": note.strip(), "basis": f.get("basis")}


def source_document(sid: str, extra: dict | None = None) -> dict:
    s = SOURCES[sid]
    out = {"title": s["title"], "publisher": s["publisher"], "url": s["url"], "secondary_urls": s.get("secondary_urls", []),
           "document_type": s.get("document_type"), "document_date": s.get("document_date"), "effective_period": s.get("effective_period"),
           "retrieved_at": s.get("retrieved_at", RETRIEVED), "retrieval_method": s.get("retrieval_method"), "pages": s.get("pages_total"),
           "sha256": "", "sha256_note": "The egress policy of the build environment blocks binary downloads from this host; the document was read "
                                        "through the sanctioned text-extraction fetch. Record the SHA-256 and re-verify each quote on its PDF page "
                                        "when the PDF is downloaded (tools/seed_presets.py).",
           "version_label": LABELS[sid], "reuse_terms": s.get("reuse_terms"), "access_limits": s.get("access_limits", []), "source_id": sid,
           "path": None}
    if extra:
        out.update(extra)
    return out


def secondary(sid: str) -> dict:
    s = SOURCES[sid]
    return {"version_label": LABELS[sid], "title": s["title"], "url": s["url"], "document_date": s.get("document_date"),
            "document_type": s.get("document_type"), "source_id": sid, "access_limits": s.get("access_limits", [])}


def unsupported(fid: str, reason: str) -> dict:
    f = fact(fid)
    return {"quote": f.get("quote"), "page": page_int(f.get("page")), "page_note": page_label(f), "doc": LABELS[f["_source"]], "reason": reason, "fact_id": fid}


def conflicts_of(*sids: str) -> list[dict]:
    out = []
    for sid in sids:
        for c in SOURCES[sid].get("conflicts", []):
            out.append({**c, "source_id": sid})
    return out


