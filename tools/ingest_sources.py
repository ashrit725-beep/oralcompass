def build_procedure_codes() -> dict:
    """Explicit mapping internal key → candidate external codes, each tied to the document where the code was printed."""
    by_key: dict[str, list[dict]] = defaultdict(list)
    seen = set()
    for sid in ("cdt-procedure-mapping", "nc-medicaid-dental-fees", "opm-fedvip-metlife-2026", "opm-fedvip-delta-2026"):
        for m in SOURCES.get(sid, {}).get("procedure_mappings", []):
            if not m.get("external_code") or not m.get("quote"):
                continue
            doc = m.get("document_id") or LABELS.get(sid) or sid
            key = (m["internal_key"], m["external_code"], doc)
            if key in seen:
                continue
            seen.add(key)
            by_key[m["internal_key"]].append({"system": m.get("external_system", "CDT"), "code": m["external_code"], "descriptor_as_printed": m.get("descriptor_as_printed"), "quote": m["quote"],
                                              "document": m.get("document") or SOURCES[sid]["title"], "document_id": doc, "document_url": m.get("document_url") or SOURCES[sid]["url"],
                                              "page": m.get("page"), "confidence": m.get("confidence"), "review": bool(m.get("review")), "notes": m.get("notes", ""), "source_id": sid})
    items = []
    for key in PROCEDURE_KEYS:
        cands = by_key.get(key, [])
        codes = Counter(c["code"] for c in cands)
        primary = codes.most_common(1)[0][0] if codes else None
        distinct = sorted(codes)
        review = (len(distinct) > 1) or any(c["review"] for c in cands) or primary is None
        items.append({"procedure_key": key, "primary_code": primary, "primary_code_document_count": codes[primary] if primary else 0, "distinct_codes_seen": distinct,
                      "review_required": review,
                      "review_reason": (None if not review else ("no code printed in any opened document" if primary is None else
                                        "more than one code could apply to this internal key — the user's own estimate/claim decides" if len(distinct) > 1 else "an extraction flagged this mapping for review")),
                      "candidates": cands})
    return {"label": "External procedure-code mappings for the 16 fixed internal procedure keys (identifiers preserved; codes shown only as printed in opened documents)",
            "policy": "Internal keys are never renamed. A mapping is a pointer to where a code was printed, not an assertion that the user's procedure IS that code; a code printed on the user's "
                      "own estimate or claim (USER) takes precedence. Mappings with review_required=true are shown with their alternatives, never silently chosen.",
            "reuse_terms": {"source_id": "ada-cdt-license-terms", "note": "CDT is copyrighted by the American Dental Association; this file does not reproduce the CDT catalog. Code numbers and descriptors appear only as printed in the cited public documents (each carries its own ADA notice)."},
            "items": items}


