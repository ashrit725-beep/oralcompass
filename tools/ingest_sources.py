def validate_plan(path: Path, j: dict) -> list[str]:
    errs = []
    code = j["plan_code"]
    for k in j.get("class_of", {}):
        if k not in PROCEDURE_KEYS:
            errs.append(f"{code}: class_of key '{k}' is not an internal procedure key")
    class_names = {c["name"] for c in j["classes"]}
    for k, v in j.get("class_of", {}).items():
        if v.get("status") not in VALID_STATUS:
            errs.append(f"{code}: class_of.{k} has invalid status {v.get('status')}")
        if v.get("value") is not None and v["value"] not in class_names:
            errs.append(f"{code}: class_of.{k} = '{v['value']}' has no class rule")
        if v.get("status") == "UNKNOWN" and v.get("value") is not None:
            errs.append(f"{code}: class_of.{k} UNKNOWN must have null value")
    for f in j.get("frequency", []):
        if f["procedure_key"] not in PROCEDURE_KEYS:
            errs.append(f"{code}: frequency key '{f['procedure_key']}' is not an internal procedure key")
        if f["clock"] not in VALID_CLOCKS:
            errs.append(f"{code}: frequency clock '{f['clock']}' invalid")
        if not isinstance(f.get("n"), int) or f["n"] <= 0:
            errs.append(f"{code}: frequency n must be a positive integer")
        if not f.get("cite"):
            errs.append(f"{code}: frequency rule for {f['procedure_key']} has no cite")
    for k in j.get("excluded", {}):
        if k not in PROCEDURE_KEYS:
            errs.append(f"{code}: excluded key '{k}' is not an internal procedure key")
    for name in ("deductible_individual", "annual_max", "benefit_year_start_month"):
        v = j.get(name)
        if not v or v.get("status") not in VALID_STATUS:
            errs.append(f"{code}: {name} missing or invalid status")
        elif v["status"] == "DOC" and not v.get("cite"):
            errs.append(f"{code}: {name} is DOC without a cite")
        elif v["status"] == "DOC" and v.get("value") is None and not v.get("unlimited"):
            errs.append(f"{code}: {name} is DOC with null value")
    for c in j["classes"]:
        for side in ("plan_share_bp_in", "plan_share_bp_out"):
            bp = c[side]["value"]
            if not (isinstance(bp, int) and 0 <= bp <= 10000):
                errs.append(f"{code}: class {c['name']} {side} out of range: {bp}")
            if not c[side].get("cite"):
                errs.append(f"{code}: class {c['name']} {side} has no cite")
    for k, v in j.get("premium_monthly", {}).items():
        if v.get("status") not in VALID_STATUS:
            errs.append(f"{code}: premium {k} invalid status")
        if v.get("value") is not None and (not isinstance(v["value"], int) or v["value"] <= 0):
            errs.append(f"{code}: premium {k} must be positive integer cents")
    # every cite must point to an existing fact with the same quote
    def walk(o):
        if isinstance(o, dict):
            if "fact_id" in o and "quote" in o and o.get("fact_id") in FACTS and FACTS[o["fact_id"]].get("quote") != o["quote"]:
                errs.append(f"{code}: cite quote differs from fact {o['fact_id']}")
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    walk(j)
    # loader round trip
    try:
        pm = load_plan(path)
        coverage_rules(pm)
    except Exception as ex:  # noqa: BLE001
        errs.append(f"{code}: loader/rules failed: {ex!r}")
    return errs


