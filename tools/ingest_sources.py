def mapping_codes(src: str) -> dict:
    """procedure_codes block for a preset: only codes printed in THIS document (from its procedure_mappings)."""
    out = {}
    for m in SOURCES[src].get("procedure_mappings", []):
        if not m.get("external_code") or not m.get("quote"):
            continue
        k = m["internal_key"]
        if k in out:
            continue
        out[k] = {"code": m["external_code"], "descriptor_as_printed": m.get("descriptor_as_printed"), "review": bool(m.get("review")),
                  "confidence": m.get("confidence"), "notes": (m.get("notes") or "")[:300],
                  "cite": {"doc": LABELS[src], "page": page_int(m.get("page")), "page_note": f"p.{m.get('page')}", "quote": m["quote"]}}
    return out


